"""R7 cross-check: the declarations read by rules.py (regular-expression reader after masking) against the TypeDef table of the built assemblies.

  python -B tools/dll-structure/cmp_typedef.py <work folder outside the repository> [--config Debug|Release]

Dumps the TypeDef table of Alundra/bin/<config>/net9.0-windows/Alundra.dll and Alundra.Tests/bin/<config>/net9.0-windows/Alundra.Tests.dll with
dump_typedefs.ps1 (pwsh, System.Reflection.Metadata, nothing loaded), reads the working tree with rules.read_tree, and compares the
top-level (namespace, name) multisets, and the nested type names. Compiler-generated types are ignored; the only gap tolerated is
`AutoGeneratedProgram` (generated by the test SDK, no source). Exit 1 on any other difference. Needs a build of the working tree.
"""
import collections
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rules  # noqa: E402
import scan_types  # noqa: E402

sys.stdout.reconfigure(encoding='utf-8')
TOLERATED_IL_ONLY = {('', 'AutoGeneratedProgram')}


def main():
    args = sys.argv[1:]
    config = 'Debug'
    if '--config' in args:
        i = args.index('--config')
        config = args[i + 1]
        del args[i:i + 2]
    if len(args) != 1:
        print(__doc__)
        return 2
    work = args[0]
    os.makedirs(work, exist_ok=True)
    decls, _paths, _srcs = rules.read_tree()
    bad = 0
    for key, proj, dll in (('dll', 'Alundra', 'Alundra.dll'), ('tests', 'Alundra.Tests', 'Alundra.Tests.dll')):
        path = os.path.join(str(scan_types.REPO), proj, 'bin', config, 'net9.0-windows', dll)
        out = os.path.join(work, 'il-%s-%s.tsv' % (key, config))
        r = subprocess.run(['pwsh', '-NoProfile', '-File', os.path.join(HERE, 'dump_typedefs.ps1'), '-Dll', path, '-Out', out], capture_output=True)
        if r.returncode != 0 or not os.path.isfile(out):
            print('ERROR: TypeDef dump of %s failed: %s' % (path, r.stderr.decode('utf-8', 'replace')))
            return 2
        il = []
        for line in open(out, encoding='utf-8'):
            ns, full, nested, _vis, gen = line.rstrip('\n').split('\t')
            if gen == '1':
                continue
            il.append((ns, re.sub(r'`\d+', '', full), nested == '1'))
        rtop = collections.Counter((d['ns'], d['name']) for d in decls[key] if not d['nested'])
        itop = collections.Counter((ns, full) for ns, full, nested in il if not nested)
        parts = {k for k, v in rtop.items() if v > 1}
        reader_only = sorted(set(rtop) - set(itop))
        il_only = sorted(set(itop) - set(rtop) - TOLERATED_IL_ONLY)
        rn = collections.Counter(d['name'] for d in decls[key] if d['nested'])
        inn = collections.Counter(full.rsplit('+', 1)[-1] for _ns, full, nested in il if nested)
        n_only = sorted((rn - inn).elements())
        i_only = sorted((inn - rn).elements())
        print('== %s (%s): reader %d top-level declarations (%d distinct, %d partial names declared several times), IL %d top-level; nested reader %d, IL %d' % (
            key, config, sum(rtop.values()), len(rtop), len(parts), sum(itop.values()), sum(rn.values()), sum(inn.values())))
        print('   reader-only: %s' % reader_only)
        print('   IL-only (AutoGeneratedProgram tolerated): %s' % il_only)
        print('   nested reader-only: %s ; nested IL-only: %s' % (n_only, i_only))
        bad += len(reader_only) + len(il_only) + len(n_only) + len(i_only)
    print('cmp_typedef: %s' % ('EQUAL' if not bad else '%d difference(s)' % bad))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
