/// <summary>
/// E20.e0b2 (docs/plan-e20-heros.md section 1.17.2, D-E0B-4, docs/plan-e20-annexe/e20-e0b/README.md): the loot roll of a creation, pure. It is the roll the binary makes as the last action of
/// <c>InitializeEntity</c> (<c>0x80032A40</c>, one caller, <c>0x80039F38</c>), through <c>ChooseRandomlyAnItem</c> (<c>0x80032968</c>) over the table <c>0x80028E0C</c> (128 rows of 16 bytes, octet <c>0x960C</c> of
/// <c>ALUN_CD.EXE</c> (France), copied byte for byte below, md5 <c>7c6b97ac50de72f436a6fbf08ed6bcd7</c>).
/// <list type="bullet">
/// <item><description><b>With a record</b>: the flag <c>f</c> is the record's <c>hu +0x10</c>, forced to 0 when <c>(f &amp; 0x7FFF) &gt;= 0x800</c>, and is what the entity keeps at <c>+0x40</c> (even when zero). If it is non-zero and its bit is raised
/// (bank <c>0x801EBA40</c> when <c>f &amp; 0x8000</c>, else <c>0x801EB344</c>, word <c>(f &gt;&gt; 5) &amp; 0x3FF</c>, bit <c>f &amp; 31</c>) the code is 0 and nothing is drawn; otherwise the code is the record's byte <c>+0x12</c> when it is non-zero, else the
/// header's <c>Contents</c> byte (<c>+0x1F</c>).</description></item>
/// <item><description><b>Without a record</b>: <c>+0x40</c> is 0 and the code is the header's byte.</description></item>
/// <item><description><b>Choosing</b>: <c>code &gt;= 0x100</c> gives 0; with bit <c>0x80</c> one step of the generator is drawn and the code becomes <c>table[(code &amp; 0x7F) * 16 + (state &gt;&gt; 28)]</c>, again; otherwise the item is the
/// code when it is below <c>0x62</c>, else 0. The table needs at most two draws.</description></item>
/// </list>
/// The class holds no state and never touches the shared stream: the caller passes the draw (<paramref name="draw"/> returns the 32-bit state of the generator AFTER its step, which is what
/// <see cref="AlundraRandom.Next"/> returns), so the same code serves the real stream and the virtual word of the measuring sink (<see cref="AlundraRandomShadow"/>). Nothing falls here: the drop at death,
/// its veto and the pickable object are E20.e0c.
/// </summary>
internal static class AlundraLootRoll
{
    /// <summary>Address of the table in the executable.</summary>
    public const uint TableAddress = 0x80028E0C;

    /// <summary>Rows of the table (<c>code &amp; 0x7F</c>).</summary>
    public const int RowCount = 128;

    /// <summary>Bytes per row (the nibble that picks the link).</summary>
    public const int RowSize = 16;

    /// <summary>The first code that is not an item: a code below it is an item as it stands, a code at or above it (and below <c>0x80</c>) gives nothing.</summary>
    public const int ItemLimit = 0x62;

    /// <summary>The first flag value (low 15 bits) the binary discards: <c>(f &amp; 0x7FFF) &gt;= 0x800</c> makes the flag 0.</summary>
    public const int FlagThreshold = 0x800;

    /// <summary>The bit of a flag that selects the temporary bank.</summary>
    public const int TemporaryBankBit = 0x8000;

    /// <summary>What a roll leaves in the entity: <c>+0x3C</c>, <c>+0x40</c>, and the number of steps drawn from the generator (0, 1 or 2).</summary>
    public readonly record struct Result(uint ItemId, int GameFlag, int Draws);

    /// <summary>The table of <c>0x80028E0C</c>, 128 rows of 16 bytes (2 048 bytes).</summary>
    internal static ReadOnlySpan<byte> Table => TableBytes;

    /// <summary>
    /// <c>ChooseRandomlyAnItem</c> (<c>0x80032968</c>): the item of a code, drawing from <paramref name="draw"/> once per chain link. <paramref name="draws"/> is the number of draws made.
    /// </summary>
    public static uint Choose(int code, Func<uint> draw, out int draws)
    {
        draws = 0;
        while (true)
        {
            if (code >= 0x100)
            {
                return 0;
            }

            if ((code & 0x80) != 0)
            {
                var state = draw();
                draws++;
                code = TableBytes[((code & 0x7F) * RowSize) + (int)(state >> 28)];
                continue;
            }

            return code < ItemLimit ? (uint)code : 0u;
        }
    }

    /// <summary>
    /// The roll <c>0x80032A40</c> of one creation. <paramref name="hasRecord"/> is whether an entity record made it; <paramref name="recordFlag"/> the record's flag word (<c>_10</c>, 16 bits), <paramref name="recordCode"/> its
    /// <c>Contents</c> (only the low byte counts), <paramref name="headerCode"/> the sprite header's <c>Contents</c> (only the low byte counts); <paramref name="state"/> holds the two flag banks.
    /// </summary>
    public static Result Roll(bool hasRecord, int recordFlag, int recordCode, int headerCode, AlundraGameState state, Func<uint> draw)
    {
        int code;
        var gameFlag = 0;
        if (!hasRecord)
        {
            code = headerCode & 0xFF;
        }
        else
        {
            gameFlag = recordFlag & 0xFFFF;
            if ((gameFlag & 0x7FFF) >= FlagThreshold)
            {
                gameFlag = 0;
            }

            if (gameFlag != 0 && ((state.GetFlag((uint)gameFlag) >> (gameFlag & 31)) & 1u) != 0)
            {
                code = 0;
            }
            else
            {
                code = (recordCode & 0xFF) != 0 ? recordCode & 0xFF : headerCode & 0xFF;
            }
        }

        var item = Choose(code, draw, out var draws);
        return new Result(item, gameFlag, draws);
    }

