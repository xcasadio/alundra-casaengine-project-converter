    /// <summary>
    /// Bit-for-bit port of <c>ScriptHelper.GetDirectionToTarget</c> (ScriptHelper.cs:23-86, address
    /// 0x8003c... - see 0x27's own opcode doc in <see cref="AlundraEventProgramRunner"/> for the one
    /// caller): resolves the packed direction (0..31) from the CALLER toward a point <paramref name="x"/>/
    /// <paramref name="y"/> pixels away (typically <c>target.PosX - self.PosX</c>, raw 16.16 fixed-point -
    /// the octant classification only depends on the x:y RATIO, so operating on the 16.16-scaled deltas
    /// directly, without first shifting them down to pixels, reproduces the same direction). Only reads
    /// x/y - no entity/world state, hence a pure static helper.
    /// </summary>
    public static uint GetDirectionToTarget(int x, int y)
    {
        var flipper = 0;

        if (y < 1)
        {
            flipper = 2;
        }

        if (x < 0)
        {
            flipper++;
        }

        if (x < 0)
        {
            x = -x;
        }

        if (y < 0)
        {
            y = -y;
        }

        var greatest = x < y ? y : x;

        var div = 0;
        var val = DivTable[div];
        if (val < (uint)greatest)
        {
            do
            {
                div++;
                val = DivTable[div];
            } while (val < (uint)greatest);
        }

        x >>= div;
        y >>= div;

        var direction = DirectionTable[y * 16 + x];

        int ret;
        if (flipper == 1)
        {
            ret = 8 - direction;
        }
        else if (flipper == 2)
        {
            ret = 0x18 - direction;
        }
        else if (flipper == 3)
        {
            ret = 8 + direction;
        }
        else // flipper == 0
        {
            ret = 0x18 + direction;
        }

        return (uint)(ret & 0x1f);
    }
