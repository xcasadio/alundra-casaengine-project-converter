import re
src = open('head/EventProgramRunner.cs').read()
i = src.index('private int Dispatch(')
body = src[i:]
ops=[0x02,0x03,0x04,0x05,0x06,0x09,0x0b,0x0c,0x0d,0x10,0x11,0x16,0x17,0x19,0x1a,0x1b,0x1c,0x24,0x25,0x27,0x28,0x2c,0x30,0x35,0x36,0x37,0x38,0x39,0x3b,0x40,0x42,0x43,0x53,0x55,0x59,0x5b,0x5c,0x62,0x87,0x89,0x8a,0x8b,0x8c,0x8e,0x8f,0xbd]
# split into case blocks
idx=[(m.start(), int(m.group(1),16)) for m in re.finditer(r'\n            case 0x([0-9A-Fa-f]{1,2}):', body)]
blocks={}
for k,(s,o) in enumerate(idx):
    e = idx[k+1][0] if k+1<len(idx) else len(body)
    blocks.setdefault(o,[]).append(body[s:e])
for o in ops:
    b=''.join(blocks.get(o,[]))
    flags=[w for w in ('Degraded','degraded','not wired','NotImplemented','stub','Stub','skip by size','TODO') if w in b]
    print('0x%02X'%o, len(b), flags)
