"""make_values_h2.py - writes ../values.md from ../out/replay_all.json and ../out/giles_ledge.json (so that no number of values.md is typed by hand).

Usage: python -B make_values_h2.py       (run scenarios_h2.py and giles_ledge_h2.py first)
"""
import sys, os, json, io
HERE = os.path.dirname(os.path.abspath(__file__))
ANNEX = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.join(ANNEX, "out")
U = 65536

R = json.load(open(os.path.join(OUT, "replay_all.json"), encoding="utf-8"))
G = json.load(open(os.path.join(OUT, "giles_ledge.json"), encoding="utf-8"))

buf = io.StringIO()
p = lambda *a: print(*a, file=buf)


def fields(r):
    return (r["posz"], r["forcez"], r["finalz"], r["coll"], r["ground"])


p("# values.md - binary values measured by the replays of E19.h2 D1 (all MEASURED on the real code of ALUN_CD.EXE; nothing inferred in this file)")
p()
p("Generated by `tools/make_values_h2.py` from `out/replay_all.json` and `out/giles_ledge.json` (produced by `tools/scenarios_h2.py` and `tools/giles_ledge_h2.py`). The full per-update tables are the files `out/replay_<case>.txt` and `out/giles_ledge.txt`.")
p()
p("## 0. Conventions")
p()
p("- Units 16.16 (1 px = 65536). `PosZ_bin` is what the binary stores; `PosZ_dll = PosZ_bin - 1` (ADR-0026); heights `h` are `(PosZ_dll - TerrainHeight) / 65536` px.")
p("- **Update k** is the physics pass `P` (0x80038364) of the tick **s+k-1**, where s is the tick of the `1A` / `1B` instruction: in one tick the binary runs the scripts (0x800386D0), the lists (0x800384F4), UpdateAnimation (0x80038E18), then P (order of UpdateEntities 0x8003B388). Update 1 is the pass that applies the impulse or the force.")
p("- `0x25` (handler 0x8003DB7C) returns 1 when `+0x140` (contact, `CollidedWithEntityZ`) or `+0x144` (`IsOnGround`) of the logic entity is non zero; it reads the pass BEFORE the tick of the script, so a condition that appears at update K makes it return at tick **s+K**.")
p("- Before the program starts, 3 passes without script settle the rest state (the DLL tests do one `calage` update). Gravity entities at rest show contact 1 and FinalForceZ -32768 at every tick.")
p("- Two engines: A = zsim (mips.py, python RunScript loop), B = vz (emu.py core, REAL RunScript 0x8004205C); two rules models: zmodel.py (+ zmodel_dll.py, binary - 1) and `M` of rules_vs_emu.py. In every case below A, B and the models agree on PosZ, ForceZ, FinalForceZ, contact, IsOnGround of every update (column `agree`).")
p("- UpdateAnimation is NOT executed: the stand-in is run_ticks.py `anim_A` (Current = Target; `+0xF8` = IZF of the animation at a change, else 0). It is valid for ONE animation change per jump.")
p()

p("## 1. Summary: when does `0x25` return?")
p()
p("| case | terrain (px) | rest PosZ_dll | last in-air height (px) | K = first update with IsOnGround or contact | `0x25` returns at | first update IsOnGround | first update contact | real program (A / B) | agree |")
p("|---|---|---|---|---|---|---|---|---|---|")
for name, r in R.items():
    rows = r["A"]
    T = r["terrain"]
    K = r["first_poll_update"]
    g1 = next((x["k"] for x in rows if x["ground"]), None)
    c1 = next((x["k"] for x in rows if x["coll"]), None)
    last_air = None
    if K and K >= 2:
        last_air = (rows[K - 2]["posz"] - 1 - T) / U
    rest = r["rest"]["posz"] - 1
    ok = (len(r["diffs"]) == 0)
    p("| %s | %.1f | %d | %s | %s | s+%s | %s | %s | s+%s / s+%s | %s |" % (name, T / U, rest, ("%.4f" % last_air) if last_air is not None else "-", K, K, g1, ("none" if c1 is None else c1), r["return_A"], r["return_B"], "yes" if ok else "NO"))
p()
p("`s+K` of the `real program` column is the tick at which the REAL script passed its `0x25` (pc moved to the instruction after it), counted from the tick of the `1A` / `1B`; it equals `s+K` of the free-standing poll in all cases.")
p()

def rel(name):
    r = R[name]
    T = r["terrain"]
    return [(x["posz"] - 1 - T, x["forcez"], x["finalz"], x["coll"], x["ground"], x["poll25_next"]) for x in r["A"]]


groups = {"IZF 1360": ["S-1360", "R-1360-Giles10", "R-1360-Bergus165", "R-1360-Bergus179", "R-1360-Bergus172"], "IZF 768": ["S-768", "R-768-Dog478a", "R-768-Dog478b"],
          "IZF 1280": ["S-1280", "R-1280-GilesAnim16"], "IZF 1024": ["S-1024", "R-1024-Bomb362"], "TR-V": ["S-TRV", "R-TRV-rec69", "R-TRV-rec81"]}
p("Real prefabs on real cells against the synthetic montage, relative to their terrain (PosZ_dll - Terrain, ForceZ, FinalForceZ, contact, IsOnGround and the `0x25` reading of every update): " + "; ".join(
  "%s: %s" % (g, "identical for " + ", ".join(n) if all(rel(x) == rel(n[0]) for x in n) else "DIFFERENT " + ", ".join(n)) for g, n in groups.items()) + ". Flags, box, OffsetZ (0 for all), terrain height (0 or 16 px) and the map's G/V (128 / 4096 on all these maps) do not change the vertical state.")
p()

p("## 2. Rows around the landing (full tables: `out/replay_<case>.txt`)")
p()
for name in ("S-1360", "S-1280", "S-768", "S-1024", "S-TRV", "S-TRV-keep"):
    r = R[name]
    rows = r["A"]
    K = r["first_poll_update"]
    T = r["terrain"]
    p("### %s - %s" % (name, r["title"]))
    p()
    air = [x["posz"] - 1 for x in rows if x["k"] < K]
    p("PosZ_dll of the updates 1 to %d: %s" % (K - 1, ", ".join(str(v) for v in air)))
    p()
    p("| k | tick | PosZ_bin | PosZ_dll | ForceZ | FinalForceZ | contact | IsOnGround | Terrain | `0x25` reads at s+k | agree |")
    p("|---|---|---|---|---|---|---|---|---|---|---|")
    for x in rows:
        if K - 2 <= x["k"] <= K + 2 or x["k"] == 1:
            i = x["k"] - 1
            agree = (fields(x) == fields(r["B"][i]) == tuple(r["models"]["Z"][i]) == tuple(r["models"]["M"][i]) == tuple(r["models"]["Zd"][i]))
            p("| %d | s+%d | %d | %d | %d | %d | %d | %d | %d | %d | %s |" % (x["k"], x["tick"], x["posz"], x["posz"] - 1, x["forcez"], x["finalz"], x["coll"], x["ground"], x["terrain"], x["poll25_next"], "yes" if agree else "NO"))
    p()

p("## 3. Giles (map 10 rec98, `C[74]` @6389 `1A [3]`), onto the 16 px ledge, real cells, real force pipeline")
p()
g = G["giles"]
p("- Start (taken from `docs/plan-e19-d2c-valeurs.md:28`, DLL-derived, NOT measured on the binary): PosX %d (%.4f px), PosY 56098816 (856 px), terrain 0; pre-jump XY force injected (walk animation 9, speed 208, direction 24, steady 159744)." % (g["x0"], g["x0"] / U))
p("- Engines A and B identical on every field of every update: **%s**." % g["engines_identical"])
p("- **K = %s**: the landing on the ledge (PosZ_dll 1048576, contact 1, IsOnGround 1) is at update %s, so `0x25 @6393` returns at tick **s+%s = F0+%s** (s = F0+101). The in-air list of PosZ (updates 1 to 18) is the list of UJ-1 (identical to the one pinned for the DLL: 348160 ... 1253376) and update 19 lands on the ledge." % (g["K"], g["K"], g["K"], 101 + g["K"]))
p("- First update whose after-pass `Terrain` (+0x138, the probe after the XY step) is the ledge: %s; the binary's ComputeZ (probe BEFORE the step) uses it from update %s; landing at %s." % (g["first_pre_step_terrain"], g["first_pre_step_terrain"] + 1, g["K"]))
p()
p("| k | tick | PosX (px) | box right edge (px) | PosZ_dll | ForceX | ForceZ | FinalForceZ | contact | IsOnGround | Terrain (px, after the pass) | `0x25` reads |")
p("|---|---|---|---|---|---|---|---|---|---|---|---|")
for x in g["rows"]:
    if x["k"] in (1, 2, 3, 4, 15, 16, 17, 18, 19, 20, 21):
        p("| %d | s+%d | %.4f | %.4f | %d | %d | %d | %d | %d | %d | %.0f | %d |" % (x["k"], x["k"] - 1, x["posx"] / U, x["posx"] / U + 10 - 1 / U, x["posz"] - 1, x["forcex"], x["forcez"], x["finalz"], x["coll"], x["ground"], x["terrain"] / U, x["poll"]))
p()
p("Sensitivity of K to the (assumed) start x and pre-jump walk force: `out/giles_ledge.txt` (coarse and 1/8 px sweeps). K = 19 for every start from %.3f px (walk animation 9) / %.3f px (walk animation 1) up to 518 px; the plan's 493.3125 px has a margin of %.2f / %.2f px. Below that start the box is not over the ledge at update 19 and Giles lands on the ground in front of the 16 px wall (K = 23)." % (
  G["giles_fine"]["9"][-1][0], G["giles_fine"]["1"][-1][0], g["x0"] / U - G["giles_fine"]["9"][-1][0], g["x0"] / U - G["giles_fine"]["1"][-1][0]))
p()

p("## 4. The ledge fall (terrain probed BEFORE the XY step)")
p()
L = G["ledge"]
p("NPC with Gravity (flags 0x180), box 20x14x32 (OffsetX -10), at rest on 16 px cells that end at x = 144 px (columns 0 to 5 high), walking east at exactly 65536 per tick (injected force) from PosX 150 px (3 rest passes first).")
p()
p("- **First tick in the air (PosZ_dll below the rest 1048576): tick %s** in engine A, **tick %s** in engine B; independent hand arithmetic (corner of the box = PosX - 10 over the high cells while < 144, terrain read before the step): tick %s. The DLL-order arithmetic (terrain read AFTER the step, mechanism (a); NOT run on the DLL) gives tick %s." % (L["first_air_A"], L["first_air_B"], L["hand_binary"], L["hand_dll_order"]))
p()
p("| t | PosX (px, after the step) | PosZ_dll | FinalForceZ | contact | IsOnGround | Terrain (after the pass) |")
p("|---|---|---|---|---|---|---|")
for x in L["rowsA"]:
    p("| %d | %.2f | %d | %d | %d | %d | %d |" % (x["k"], x["posx"] / U, x["posz"] - 1, x["finalz"], x["coll"], x["ground"], x["terrain"]))
p()
p("At tick 4 the pre-step probe still sees the 16 px cells (landing test passes, contact 1) while the post-step probe sees 0: `IsOnGround` is already 0 (FloorHeight is computed from the post-step terrain) with PosZ still at 16 px; the entity starts to fall at tick 5.")
p()

p("## 5. Self-checks that produced no disagreement")
p()
p("- `out/rules_vs_emu.out`: independent rules model against the real code, 700 scenarios x 30 ticks = 21000 ticks, 0 mismatch (tools/rules_vs_emu.py, engine vz/emu.py).")
p("- `out/zmodel_dll.out`: `binary - 1` equals the DLL-native formulation on 200000 random 6-tick runs.")
p("- `out/validate.out`: zmodel.py against the real code run by zsim (460 scenarios x 40 ticks + 3000 handler pairs) and the three mutation checks (tools/validate.py) - see the file.")
p("- `scen_real.out` and `traces.out` of `docs/plan-e19-h1b2-annexe/` are reproduced byte for byte by the annex copies of the tools (`tools/scen_real.py`, `tools/traces.py`): see README.md.")
p("- `out/replay_summary.txt`: %d cases, engines A / B / models Z, Zd, M: %d disagreements in total." % (len(R), sum(len(r["diffs"]) for r in R.values())))

open(os.path.join(ANNEX, "values.md"), "w", encoding="utf-8").write(buf.getvalue())
print("values.md written,", len(buf.getvalue()), "bytes")
