"""mymodel_fuzz.py - MY OWN model of the wind-1 driver 0x80035EB0 written from MY reading of the disassembly (see report), fuzzed against the REAL code run by MY interpreter
(mymips.py) on states generated by MY generator. The Hoare sort (0x8003AE04) is not re-modelled here: the model's query lists the survivors of the filters and then calls the
real sort through the interpreter (the sort was independently modelled by the h4b critic); the filters, the key, the Z gate, the last-target test, the 0x6401 test, the draws, the
spawn arguments, the +0x144 branch, the end of the table, the phases and the guard are mine.
usage: python -B mymodel_fuzz.py N SEED [mutant]"""
import random
import sys
import copy
import mymips as X

HERO = 0x80127D30
STRIDE = 0x294
M32 = X.M32
TABLE = [30, 40, 50, 60, 70, 80, 90, 100, 0xFFFF]
PH, CNT, ITEM, LAST, RNG, COUNTW = 0x80127160, 0x8012715C, 0x80127164, 0x8012712C, 0x80098708, 0x80134360
FICHE_BASE = 0x80150000
STUB_ENT = 0x80160000        # the entity "returned" by the stubbed SpawnWarpEntity


def ep(k):
    return HERO + STRIDE * k


def s32(x):
    return X.s32(x)


def lcg(s):
    return (s * 0x7D2B89DD + 0xE06A02E7) & M32


def gen_state(rnd):
    st = {}
    live = rnd.random() < 0.7
    st['phase'] = rnd.choice([1, 1, 1, 0, 0, 2, 2, -1, 3, 7]) if not live else rnd.choice([1, 1, 1, 1, 0])
    st['counter'] = rnd.choice([rnd.randrange(0, 140), 30, 40, 50, 60, 70, 80, 90, 100, 29, 31, 99, 101, 102, 0, 65000]) if not live else rnd.choice([30, 40, 50, 60, 70, 80, 90, 100, 100, 101, 35, 99])
    st['item'] = rnd.choice([0x31, 0x31, 0, 0x2B, 0x60, 0x20])
    st['anim'] = rnd.choice([0x33, 0x33, 0x33, 0x32, 0x34, 0x31, 0, 0x2D]) if not live else rnd.choice([0x33] * 8 + [0x32, 0x34, 0x31])
    st['slope'] = rnd.choice([0, 0, 0, 4, 1, 2]) if not live else rnd.choice([0] * 12 + [4])
    st['rng'] = rnd.getrandbits(32)
    st['hx'] = rnd.randrange(0, 300) << 16 | rnd.choice([0, 0, rnd.getrandbits(16)])
    st['hy'] = rnd.randrange(0, 300) << 16 | rnd.choice([0, 0, rnd.getrandbits(16)])
    st['hz'] = rnd.choice([0, 1, 0x10000, 0x100000, 0xFFFF0000, 0xFFF00000, rnd.randrange(-0x2000000, 0x2000000) & M32])
    nslots = rnd.choice([0, 1, 2, 3, 4, 5, 8]) if not live else rnd.choice([1, 2, 2, 3, 3, 4, 5, 6])
    ents = {}
    for k in range(1, nslots + 1):
        near = rnd.random() < 0.6
        dxp = rnd.choice([0, 20, 40, 100, 159, 160, 161, 200, 400, 1000, -40, -160, -161, -400, 3000, -3000, 32767, -32768])
        dyp = rnd.choice([0, 20, 40, 100, 159, 160, 161, 200, -40, -161, 5000])
        if near:
            dxp = rnd.randrange(-60, 60)
            dyp = rnd.randrange(-60, 60)
        ex = (st['hx'] + (dxp << 16) + rnd.choice([0, 0, 1, 0xFFFF, rnd.getrandbits(16)])) & M32
        ey = (st['hy'] + (dyp << 16) + rnd.choice([0, 0, 1, 0xFFFF, rnd.getrandbits(16)])) & M32
        ez = (st['hz'] + rnd.choice([0, 0, 0x500000, 0x500001, 0x4FFFFF, -0x500000, 0x1000000, -1, 0x7000000])) & M32
        e = dict(status=rnd.choice([2, 2, 2, 3, 1, 4, 0]) if not live else rnd.choice([2] * 8 + [3, 1, 4]), f20=rnd.choice([0, 0, 0, 0, 5]) if not live else rnd.choice([0] * 12 + [5]),
                 flags=rnd.choice([1, 1, 1, 0x4, 0x5, 0, 0x2005]) if not live else rnd.choice([1] * 10 + [0x4, 0x5]),
                 c1d0=rnd.choice([0, 0, 0, 0, 25]) if not live else rnd.choice([0] * 12 + [25]), c1cc=rnd.choice([0, 0, 0, 0, 3]) if not live else rnd.choice([0] * 12 + [3]),
                 b4=rnd.choice([0, 0, 0, 0x40, 0x41, 0x1]) if not live else rnd.choice([0] * 12 + [0x40, 0x1]),
                 has_fiche=rnd.random() < (0.9 if not live else 0.97), resp=rnd.choice([16, 16, 16, 0x80, 0xC0, 0x40, 0, 0x81, 0xBF, 0x20, 0x90]) if not live else rnd.choice([16] * 8 + [0x80, 0xC0, 0x40, 0]), x=ex, y=ey, z=ez)
        ents[k] = e
    st['ents'] = ents
    st['count'] = max(0, nslots + (rnd.choice([-1, 0, 0, 1, 2]) if not live else rnd.choice([1, 1, 2, 0, -1])))
    if st['count'] < 0:
        st['count'] = 0
    # last target: 0, a pointer of an existing slot, or an arbitrary slot
    st['last'] = rnd.choice([0, 0] + ([ep(k) for k in ents] if ents else []) + [ep(rnd.randrange(1, 6))])
    st['spawn_ret'] = rnd.choice([0, STUB_ENT, STUB_ENT])
    st['ground'] = rnd.choice([0, 0, 1, 0x200])
    return st


def build(mem, st):
    mem.poke(PH, 4, st['phase'] & M32)
    mem.poke(CNT, 4, st['counter'] & M32)
    mem.poke(ITEM, 4, st['item'])
    mem.poke(LAST, 4, st['last'])
    mem.poke(RNG, 4, st['rng'])
    mem.poke(COUNTW, 4, st['count'])
    mem.poke(HERO + 0x88, 4, st['anim'])
    mem.poke(HERO + 0x18C, 4, st['slope'])
    mem.poke(HERO + 0x114, 4, st['hx'])
    mem.poke(HERO + 0x118, 4, st['hy'])
    mem.poke(HERO + 0x11C, 4, st['hz'])
    mem.poke(STUB_ENT + 0x144, 4, st['ground'])
    for k, e in st['ents'].items():
        b = ep(k)
        mem.poke(b + 0x10, 4, e['status'])
        mem.poke(b + 0x20, 4, e['f20'])
        mem.poke(b + 0x6C, 4, e['flags'])
        mem.poke(b + 0x1D0, 4, e['c1d0'])
        mem.poke(b + 0x1CC, 4, e['c1cc'])
        mem.poke(b + 0xB4, 4, e['b4'])
        fp = FICHE_BASE + 0x100 * k if e['has_fiche'] else 0
        mem.poke(b + 0x1C4, 4, fp)
        if fp:
            for t in range(0, 16):
                mem.poke(fp + 2 + t, 1, e['resp'] if t == 11 else 16)
        mem.poke(b + 0x114, 4, e['x'])
        mem.poke(b + 0x118, 4, e['y'])
        mem.poke(b + 0x11C, 4, e['z'])


def real(st):
    mem = X.Mem(strict=False)
    build(mem, st)
    spawns, destroys = [], []

    def h_spawn(c):
        spawns.append([c.r[4], c.r[5], c.r[6], c.r[7], c.m.rd(c.r[29] + 0x10, 4), c.m.rd(c.r[29] + 0x14, 4), c.m.rd(c.r[29] + 0x18, 4)])
        c.r[2] = st['spawn_ret']

    def h_destroy(c):
        destroys.append(c.r[4])
        c.r[2] = 0

    cpu = X.CPU(mem, hooks={0x80039F58: h_spawn, 0x8003A774: h_destroy})
    ret = cpu.run(0x80035EB0, sp=0x801FFF00)
    rd = lambda a: mem.rd(a, 4, fetch=True)
    out = dict(ret=ret, phase=s32(rd(PH)), item=rd(ITEM), last=rd(LAST), rng=rd(RNG), anim=rd(HERO + 0x88), counter=rd(CNT),
               spawns=spawns, destroys=destroys, forcez=(rd(STUB_ENT + 0xB8) if (STUB_ENT + 0xB8) in mem.written or True else None),
               forcez_written=any(a == STUB_ENT + 0xB8 for (a, n, v) in mem.logw))
    # the sort/query are real; capture the arrays for the 'query' comparison
    out['ptrs'] = []
    return out, mem


def model(st, mut=frozenset()):
    """MY model"""
    o = dict(ret=0, phase=st['phase'], item=st['item'], last=st['last'], rng=st['rng'], anim=st['anim'], counter=st['counter'], spawns=[], destroys=[],
             forcez_written=False, forcez=None)
    # what the stub entity holds
    o['forcez'] = 0

    def cancel():
        it = o['item']
        if it == 0:
            return
        if (it - 0x1F) & M32 >= 0x14:
            o['item'] = 0                      # out of range: 0x800351A0
            return
        # in range: the table entry; only the neutral ones are modelled (0x31, 0x2B)
        if it in (0x31, 0x2B):
            o['item'] = 0
        else:
            raise NotImplementedError

    def guard():
        if st['slope'] == 4:
            cancel()
            return 1
        if o['anim'] in (0x32, 0x33):
            return 0
        cancel()
        return 1

    def query():
        res = []
        for k in range(1, st['count']):
            e = st['ents'].get(k)
            if e is None:
                continue
            if ep(k) == HERO:
                continue
            if e['status'] not in (2, 3):
                continue
            if e['f20'] != 0:
                continue
            if (e['flags'] & 1) == 0:
                continue
            if e['c1d0'] != 0 or e['c1cc'] != 0:
                continue
            if e['b4'] & 0x40:
                continue
            if not e['has_fiche']:
                continue
            if (e['resp'] & 0xC0) == 0x80:
                continue
            dx = s32((e['x'] - st['hx']) & M32) >> 16
            dy = s32((e['y'] - st['hy']) & M32) >> 16
            res.append((ep(k), (dx * dx + dy * dy) & M32))
        # (entities in slots >= len(ents)+1 that are not in the dict are absent: status 0)
        return res

    def strike(sort_fn):
        res = query()
        if len(res) >= 3:
            res = sort_fn(res)
        sel = 0
        for (p, key) in res:
            k = (p - HERO) // STRIDE
            e = st['ents'][k]
            if s32((st['hz'] + 0x500000) & M32) < s32(e['z']):
                continue
            if p == o['last']:
                continue
            if s32(key) < 0x6401:
                sel = p
                break
            break
        if sel:
            k = (sel - HERO) // STRIDE
            e = st['ents'][k]
            o['spawns'].append([HERO, 0, 0x16, e['x'], e['y'], (e['z'] + 0x800000) & M32, 0])
            if st['spawn_ret']:
                o['forcez_written'] = True
                o['forcez'] = 0xFFF80000
            o['last'] = sel
            return
        s1 = lcg(o['rng'])
        s2 = lcg(s1)
        o['rng'] = s2
        x = (st['hx'] + ((s1 * 0xC00001) >> 32) - 0x600000) & M32
        y = (st['hy'] + ((s2 * 0x800001) >> 32) - 0x400000) & M32
        z = (st['hz'] + 0x800000) & M32
        o['spawns'].append([HERO, 0, 0x16, x, y, z, 0])
        if st['spawn_ret']:
            if st['ground'] != 0:
                o['destroys'].append(st['spawn_ret'])
            else:
                o['forcez_written'] = True
                o['forcez'] = 0xFFF80000
        o['last'] = 0

    def p1(sort_fn):
        g = guard()
        if g:
            return 1
        if o['anim'] != 0x33:
            return 0
        c = st['counter']
        if s32(c) < TABLE[0]:
            return 0
        i = 0
        while True:
            if TABLE[i] == c:
                strike(sort_fn)
            i += 1
            if not (s32(c) >= TABLE[i]):
                break
        if TABLE[i] == 0xFFFF:
            o['anim'] = 0x34
            o['phase'] += 1
        return 0

    sort_fn = real_sort
    ph = st['phase']
    if ph == 1:
        o['ret'] = p1(sort_fn)
    elif ph == 0:
        o['last'] = 0
        o['phase'] = 1
        o['ret'] = p1(sort_fn)
    elif ph == 2:
        o['ret'] = 1 if o['anim'] != 0x34 else 0
    else:
        o['ret'] = 0
    return o


def real_sort(res):
    """call the REAL sort 0x8003AE04 (through my interpreter) on the (pointer, key) list"""
    mem = X.Mem(strict=False)
    P, K = 0x800CC058, 0x800CC158
    for i, (p, key) in enumerate(res):
        mem.poke(P + 4 * i, 4, p)
        mem.poke(K + 4 * i, 4, key)
    cpu = X.CPU(mem)
    cpu.run(0x8003AE04, args=(P, K, 0, len(res) - 1))
    out = []
    for i in range(len(res)):
        out.append((mem.rd(P + 4 * i, 4, fetch=True), mem.rd(K + 4 * i, 4, fetch=True)))
    return out


def main():
    n = int(sys.argv[1])
    seed = int(sys.argv[2])
    rnd = random.Random(seed)
    bad = 0
    skipped = {}
    stats = dict(strike_target=0, strike_random=0, sorted=0, endcalls=0, ground_branch=0, guard_cancel=0)
    for it in range(n):
        st = gen_state(rnd)
        try:
            r, mem = real(st)
        except Exception as ex:                                   # e.g. a cancel dispatch to an unmodelled item
            skipped['real_exc'] = skipped.get('real_exc', 0) + 1
            continue
        try:
            m = model(st)
        except NotImplementedError:
            skipped['model_ni'] = skipped.get('model_ni', 0) + 1
            continue
        keys = ['ret', 'phase', 'item', 'last', 'rng', 'anim', 'counter', 'spawns', 'destroys', 'forcez_written']
        diff = [k for k in keys if (r[k] & M32 if isinstance(r[k], int) and k in ('ret', 'item', 'last', 'rng', 'anim', 'counter') else r[k]) != (m[k] & M32 if isinstance(m[k], int) and k in ('ret', 'item', 'last', 'rng', 'anim', 'counter') else m[k])]
        if r['forcez_written'] and m['forcez_written'] and r['forcez'] != m['forcez']:
            diff.append('forcez')
        if m['spawns']:
            stats['strike_target' if m['spawns'][0][3] in [e['x'] for e in st['ents'].values()] and m['rng'] == st['rng'] else 'strike_random'] += 1
        if m['destroys']:
            stats['ground_branch'] += 1
        if diff:
            bad += 1
            if bad <= 5:
                print('MISMATCH', it, diff, {k: (r[k], m[k]) for k in diff if k in r})
    print('%d states (seed %d): %s ; %s ; skipped %s' % (n, seed, 'no mismatch' if not bad else '%d MISMATCH' % bad, stats, skipped))


main()
