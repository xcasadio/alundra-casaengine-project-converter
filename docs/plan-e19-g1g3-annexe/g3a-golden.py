"""E19.g G3a-0: generates g3a-golden.tsv, the values the reservoir tests of G3a are written against.

Every value comes from an oracle of the binary (anims_oracle.json, load_oracle.json, scenarios_out.txt: the real code of
ALUN_CD.EXE run in the MIPS interpreter) or from the G1 export (alundra-project, only for what the oracles do not carry:
the frame lists and the zones), cross-checked against the oracles. Nothing is typed by hand. Usage:

    python g3a-golden.py            writes g3a-golden.tsv next to this script
    python g3a-golden.py --check    fails when the committed table differs from what the oracles give

Sections (first column):
  A  animation: key (m<map>:<effect>:<anim> map table, g:<effect>:<anim> global table), end, life S (sum of the delays), last drawn tick
     (S for a Destroy animation, - for a loop), free tick (S + 1 or -), images of the first image set, IDSV of the first image set,
     the frames as ticks:set;ticks:set. Ticks count from 0 (anims_oracle.json counts from 1: its observed_destroy_tick is S + 1 and its
     observed_free_tick is S + 2, both 1-based).
  L  load: map, slot, record, x px, y px, z px of the slots at the entry with the hero on the tile (0, 0).
  Z  the records that appear at load and whose zone does not contain the tile (0, 0): map, record, x1, y1, x2, y2.
  S  scenarios of the binary: S163 (rays: tick, active count), S391 (slot, record, x, y, z in 16.16, animation), S476 (aura: last drawn,
     freed, depth at tick 0, revive: ticks run, status 60 ticks later).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
PROJECT = os.path.join(ROOT, "alundra-project")


def load_export():
    index = json.load(open(os.path.join(PROJECT, "Maps", "world-index.json"), encoding="utf-8"))
    maps = {}
    for map_id, rel in index.items():
        folder = os.path.join(PROJECT, os.path.dirname(rel.replace("\\", os.sep)))
        name = os.path.basename(folder)
        path = os.path.join(folder, "effects", name + ".effects.json")
        if os.path.exists(path):
            maps[int(map_id)] = json.load(open(path, encoding="utf-8"))
    glob = json.load(open(os.path.join(PROJECT, "Data", "effects", "effects-global.json"), encoding="utf-8"))
    return maps, glob


def table_of(key, maps, glob):
    parts = key.split(":")
    if parts[0] == "g":
        return glob["Effects"][int(parts[1])], int(parts[2])
    return maps[int(parts[0][1:])]["Effects"][int(parts[1])], int(parts[2])


def main():
    anims = json.load(open(os.path.join(HERE, "anims_oracle.json")))
    load = json.load(open(os.path.join(HERE, "load_oracle.json")))
    scen = open(os.path.join(HERE, "scenarios_out.txt"), encoding="utf-8").read()
    maps, glob = load_export()
    out = []
    out.append("# E19.g G3a golden table, generated by g3a-golden.py from anims_oracle.json, load_oracle.json, scenarios_out.txt (the binary) and the G1 export.")
    out.append("# A: key end life last_drawn free_tick first_nimg first_idsv frames | L: map slot record x_px y_px z_px | Z: map record x1 y1 x2 y2 | S: scenarios")

    # --- A: animations ---
    ndiff = []
    for key in sorted(anims, key=lambda k: (k[0] != "g", int(k.split(":")[0][1:]) if k[0] == "m" else 0, int(k.split(":")[1]), int(k.split(":")[2]))):
        o = anims[key]
        table, ai = table_of(key, maps, glob)
        anim = table["Animations"][ai]
        frames = anim["Frames"]
        life = sum(f[0] for f in frames)
        end = anim["End"].lower()
        assert end == o["model_end"], (key, end, o["model_end"])
        assert life == o["model_life"], (key, life, o["model_life"])
        assert len(frames) == o["nframes"], (key, len(frames), o["nframes"])
        first = table["ImageSets"][frames[0][1]]
        if len(first["Images"]) != o["first_nimg"]:
            ndiff.append((key, len(first["Images"]), o["first_nimg"]))
        assert first["Idsv"] == o["first_bias"], (key, first["Idsv"], o["first_bias"])
        if end == "destroy":
            assert o["observed_destroy_tick"] == life + 1 and o["observed_free_tick"] == life + 2 and o["pushed"] == life + 1, key
            last, free = str(life), str(life + 1)
        else:
            assert o["observed_destroy_tick"] is None and o["pushed"] == o["ticks_run"], key
            last, free = "-", "-"
        # first_nimg of the oracle counts the degenerate images of the binary: keep the oracle value, and the export value when it differs.
        nimg = o["first_nimg"]
        fr = ";".join("%d:%d" % (f[0], f[1]) for f in frames)
        out.append("\t".join(["A", key, end, str(life), last, free, str(nimg), str(first["Idsv"]), fr, str(len(first["Images"]))]))
    out.insert(2, "# A also carries, last, the images of the first image set in the export (it differs from first_nimg only where degenerate images were dropped)")

    # --- L: load slots (hero on the tile (0, 0)), and Z: restricted zones ---
    nload = 0
    for m in sorted(load, key=int):
        for slot, rec in enumerate(load[m]):
            assert rec[0] >= 0
            out.append("\t".join(["L", m, str(slot), str(rec[0]), str(rec[1]), str(rec[2]), str(rec[3])]))
            nload += 1
    assert nload == 245, nload
    restricted = 0
    total_spawn = 0
    for m in sorted(maps):
        for i, r in enumerate(maps[m]["Records"]):
            if r["Flags"] & 0x40:
                total_spawn += 1
                if not (r["X1"] <= 0 <= r["X2"] and r["Y1"] <= 0 <= r["Y2"]):
                    out.append("\t".join(["Z", str(m), str(i), str(r["X1"]), str(r["Y1"]), str(r["X2"]), str(r["Y2"])]))
                    restricted += 1
                    assert i not in [x[0] for x in load[str(m)]], (m, i)
    assert total_spawn == 251 and restricted == 6, (total_spawn, restricted)
    # each oracle slot is a record of the export at the position the rule gives
    for m, slots in load.items():
        for rec in slots:
            r = maps[int(m)]["Records"][rec[0]]
            assert r["Flags"] & 0x40 and rec[1] == r["X"] * 12 + 12 and rec[2] == r["Y"] * 8 + 8 and rec[3] == r["Z"] * 8, (m, rec, r)

    # --- S: scenarios ---
    sec = re.search(r"S1 map 391 after map load.*?\n(.*?)\nS1 after tick 0", scen, re.S).group(1)
    n391 = 0
    for line in sec.splitlines():
        mt = re.match(r"\s*slot (\d+): record (\d+) x=(\d+) y=(\d+) z=(\d+) \(px (\d+) (\d+) (\d+)\) target sprite (\d+) anim (\d+) bank (\d+) status (\d+)", line)
        if mt:
            g = list(map(int, mt.groups()))
            out.append("\t".join(["S", "S391", str(g[0]), str(g[1]), str(g[2]), str(g[3]), str(g[4]), str(g[9])]))
            n391 += 1
    assert n391 == 5
    s3 = re.search(r"S3 map 163 after load.*?active slots per tick: \[(.*?)\]\n", scen, re.S).group(1)
    pairs = re.findall(r"\((\d+), (\d+)\)", s3)
    assert len(pairs) == 15
    for t, c in pairs:
        out.append("\t".join(["S", "S163", t, c]))
    m476 = re.search(r"first tick with dead flag: (\d+) ; last tick drawn \(status != 0\): (\d+)\n\s*slot freed at tick: (\d+)\n\s*depth at tick 0: (\d+) OT (\d+)", scen)
    out.append("\t".join(["S", "S476", "dead", m476.group(1), "last_drawn", m476.group(2), "freed", m476.group(3), "depth0", m476.group(4)]))
    for n, st in re.findall(r"applied after (\d+) ticks -> slot status after 60 more ticks: (\d)", scen):
        out.append("\t".join(["S", "S476-revive", n, st]))
    # the aura animation of the oracle: map 476, effect 0, animation 0 (Destroy) and 1 (Loop)
    a0 = anims["m476:0:0"]
    assert a0["observed_destroy_tick"] - 1 == int(m476.group(2)) and a0["observed_free_tick"] - 1 == int(m476.group(3)), a0
    # 163 rays: animation 1 of table 0, the binary frees at tick 11
    a163 = anims["m163:0:1"]
    assert a163["observed_free_tick"] - 1 == 11
    text = "\n".join(out) + "\n"
    path = os.path.join(HERE, "g3a-golden.tsv")
    if "--check" in sys.argv:
        cur = open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n")
        if cur != text:
            print("g3a-golden.tsv differs from the oracles")
            sys.exit(1)
        print("g3a-golden.tsv matches (%d lines)" % len(out))
        return
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    print("wrote %s (%d lines; first_nimg differs from the export on %d animations: %s)" % (path, len(out), len(ndiff), ndiff[:6]))


main()
