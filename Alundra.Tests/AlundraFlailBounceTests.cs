    /// <summary>Where a probe starts: the position of the hero, his animation and forces (the machine's row 0, <c>pre</c> of <c>attack.run</c>) and the counter <c>+0x1C</c> of that row.</summary>
    private readonly record struct ProbeStart(float X, uint Anim, int ForceX, int FrameCounter);

    // F-iron-walk: after the warm-up (Right held until two ticks of Moving at ForceX 159744), the hero is at pixel 6952960 / 65536, animation 1, force 159744, the counter +0x1C is 3 (row 0 of the machine).
    private static readonly ProbeStart StartAtRest = new(100f, 0, 0, 0);
    private static readonly ProbeStart StartWalking = new(6952960 / 65536f, 1, 159744, 3);

    private sealed record MontageResult(List<string> Diffs, Dictionary<int, List<string>> StubsByTick);

    /// <summary>
    /// Runs a probe: the pad word of each row of the oracle is held one tick per frame; before tick <paramref name="pokeTick"/> the harness sets <c>HitCounter</c> to 1, as the oracle's
    /// <c>before</c> does (the hit pass that would write it is not in the montage). The montage has no counters pass (that is the world's): after each tick the harness clears
    /// <c>HitCounter</c> and counts <c>FrameCounter</c> up, as <c>0x80038998</c> does. The result lists every difference with the oracle and the stubs called at each tick.
    /// </summary>
    private static MontageResult RunProbe(string name, int item, ProbeStart start, int? pokeTick)
    {
        var rows = FlailProbe.Load(name);
        var callers = FlailProbe.Callers(name);
        var rig = JumpHeroRig.Build(x: start.X, y: 100f, z: 0f, freePad: true, attackClock: true);
        var sounds = new RecordingSoundPlayer();
        rig.Host.SoundPlayer = sounds;
        Equip(rig.Host, item);

        var hero = rig.Hero;
        hero.TargetDirection = 24;
        hero.AnimationDirection = 3; // right: east.
        hero.CurrentAnimationId = ~hero.TargetAnimationId;
        rig.Step(); // the first switch (the sprite takes the animation 0, right) is resolved.
        sounds.Requests.Clear();
        if (start.Anim != 0)
        {
            hero.TargetAnimationId = start.Anim;
            hero.CurrentAnimationId = start.Anim;
        }

        hero.TargetDirection = 24;
        hero.ForceX = start.ForceX;
        hero.FrameCounter = start.FrameCounter;

        var diffs = new List<string>();
        var stubsByTick = new Dictionary<int, List<string>>();
        var landingTicks = new HashSet<int>(callers.Where(c => c.Origin == FlailProbe.CreatePlayerAnimationEffects && c.Kind == "sound" && c.Id == 11).Select(c => c.Tick));
        foreach (var row in rows)
        {
            sounds.Requests.Clear();
            var calls = new List<(int, string, uint)>();
            PlayerAnimationEffects.StubCallsForTests = calls;
            if (row.Tick == pokeTick)
            {
                hero.HitCounter = 1;
            }

            rig.Step(row.Hold);
            PlayerAnimationEffects.StubCallsForTests = null;
            hero.HitCounter = 0; // the counters pass of the world (0x80038998), absent from the montage.
            hero.FrameCounter++;
            stubsByTick[row.Tick] = calls.Select(c => c.Item2).ToList();

            void Check(string field, long dll, long oracle)
            {
                if (dll != oracle)
                {
                    diffs.Add($"{name} tick {row.Tick} {field}: dll {dll}, oracle {oracle}");
                }
            }

            Check("anim_target", hero.TargetAnimationId, row.AnimTarget);
            Check("anim_cur", hero.CurrentAnimationId, row.AnimCurrent);
            Check("force_x", hero.ForceX, row.ForceX);
            Check("force_y", hero.ForceY, row.ForceY);
            Check("force_z", hero.ForceZ, row.ForceZ);
            Check("pos_z", hero.PosZ, row.PosZDll);
            Check("on_ground", hero.IsOnGround, row.OnGround);
            Check("rec_ptr", hero.WeaponRecordPointer, row.RecPtr);
            Check("rec_cnt", hero.WeaponStepCounter, row.RecCnt);

            // THE EXCLUSION, written once: the sounds the function asks at its head - the landing sound 11 (its dust, the effect 7, is no sound) - are the named stub's business; the DLL asks none. Every other
            // sound is compared, and `sound(0)` is the function with "no sound" (the animation set of the switch, or the step table of a flat slope), never a sound.
            var oracleSounds = row.Sounds.Where(s => !(s == 11 && landingTicks.Contains(row.Tick))).OrderBy(s => s);
            var dllSounds = sounds.Requests.OrderBy(s => s);
            if (!oracleSounds.SequenceEqual(dllSounds))
            {
                diffs.Add($"{name} tick {row.Tick} sounds: dll [{string.Join(",", dllSounds)}], oracle [{string.Join(",", oracleSounds)}]");
            }
        }

        return new MontageResult(diffs, stubsByTick);
    }

    private static void AssertEqualToOracle(MontageResult result)
        => Assert.True(result.Diffs.Count == 0, $"{result.Diffs.Count} differences with the oracle; the first ones:{Environment.NewLine}{string.Join(Environment.NewLine, result.Diffs.Take(12))}");

    /// <summary>
    /// The exclusion's other half: at each tick where the oracle's function asked the landing sound 11 and its dust, the landing stub is called, and at no other tick; at each tick where it asked a step
    /// <c>sound(0)</c> the walk stub is called. Ticks are those of <c>F-sound-callers.txt</c> (the return address of each call inside <c>0x8002FB14-0x80030678</c>).
    /// </summary>
    private static void AssertStubsAtTheTicksOfTheOracle(string probe, MontageResult result, int[] landingTicks, int[] stepTicks)
    {
        var fromTheFunction = FlailProbe.Callers(probe).Where(c => c.Origin == FlailProbe.CreatePlayerAnimationEffects).ToList();
        Assert.Equal(landingTicks, fromTheFunction.Where(c => c.Kind == "sound" && c.Id == 11).Select(c => c.Tick).Distinct().OrderBy(t => t).ToArray());
        Assert.Equal(landingTicks, fromTheFunction.Where(c => c.Kind == "effect" && c.Id == 7).Select(c => c.Tick).Distinct().OrderBy(t => t).ToArray());
        Assert.Equal(stepTicks, fromTheFunction.Where(c => c.Kind == "sound" && c.Id == 0).Select(c => c.Tick).Distinct().OrderBy(t => t).ToArray());

        Assert.Equal(landingTicks, result.StubsByTick.Where(p => p.Value.Contains(PlayerAnimationEffects.LandingStubName)).Select(p => p.Key).OrderBy(t => t).ToArray());
        foreach (var tick in stepTicks)
        {
            Assert.Contains(PlayerAnimationEffects.WalkStepStubName, result.StubsByTick[tick]);
        }
    }

