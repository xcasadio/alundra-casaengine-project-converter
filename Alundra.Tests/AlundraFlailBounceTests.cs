    [Fact]
    public void TheCellReader_IsThe52x60GridOfARealMap_AndSeesALiveMutationOfTheStore()
    {
        // The real map 14 (Overworld 3,1-14), 52 x 60 like all 483 maps: the cells below are read from its export (height / walkability). The store of E7 mutates the arrays the field aliases (a lever
        // opening a door): the reader of the flail sees it at once.
        var tileMapPath = System.IO.Path.Combine(ProjectRootFinder.Find(), "Maps", "Overworld", "Overworld 3,1-14", "tilemap", "Overworld 3,1-14.tileMap");
        var tileMapData = new CasaEngine.Framework.Assets.TileMap.TileMapData();
        tileMapData.Load(Newtonsoft.Json.Linq.JObject.Parse(System.IO.File.ReadAllText(tileMapPath)));
        Assert.True(CellsCollisionField.TryCreate(tileMapData, "Overworld 3,1-14", out var field, out var records));
        Assert.True(CellStore.TryCreate(records!, tileMapData.MapSize.Width, tileMapData.MapSize.Height, "Overworld 3,1-14", out var store));
        Assert.Equal((52, 60), (tileMapData.MapSize.Width, tileMapData.MapSize.Height));

        Assert.True(field!.TryReadBinaryCell(7, 8, out var height, out var walkability));
        Assert.Equal((18, 0x41), (height, walkability)); // a wall of the hill: height 18, walkability 0x41.
        Assert.True(field.TryReadBinaryCell(8, 9, out height, out walkability));
        Assert.Equal((9, 0x01), (height, walkability));
        Assert.True(field.TryReadBinaryCell(3, 3, out height, out walkability));
        Assert.Equal((0, 0), (height, walkability));

        store!.SetCellBits(3, 3, 0x40, 0);
        Assert.True(field.TryReadBinaryCell(3, 3, out height, out walkability));
        Assert.Equal((0, 0x40), (height, walkability));
        store.CopyCellRectangle(7, 8, 1, 1, 4, 3);
        Assert.True(field.TryReadBinaryCell(4, 3, out height, out walkability));
        Assert.Equal((18, 0x41), (height, walkability));

        Assert.True(field.TryReadBinaryCell(51, 59, out _, out _));
        Assert.False(field.TryReadBinaryCell(52, 0, out height, out walkability));
        Assert.Equal((0, 0), (height, walkability));
        Assert.False(field.TryReadBinaryCell(0, 60, out _, out _));
        Assert.False(field.TryReadBinaryCell(-1, 0, out _, out _));
    }

