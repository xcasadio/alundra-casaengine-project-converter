    private static readonly Regex SweepLine = new(@"^(-?\d+)\t(-|\d+)\t(-|\d+)$", RegexOptions.Compiled);

    private static Dictionary<int, int?> ReadXSweep()
    {
        var table = new Dictionary<int, int?>();
        foreach (var line in File.ReadAllLines(Path.Combine(HitOracleTrace.OutputFolder(), "reach-sweep.txt")))
        {
            var match = SweepLine.Match(line);
            if (match.Success)
            {
                table[int.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture)] =
                    match.Groups[2].Value == "-" ? null : int.Parse(match.Groups[2].Value, CultureInfo.InvariantCulture);
            }
        }

        return table;
    }

    private static Dictionary<(int Dx, int Dy), int> ReadYWindows()
    {
        var table = new Dictionary<(int, int), int>();
        var windowLine = new Regex(@"^dx (-?\d+): contact for dy in \[(-?\d+), (-?\d+)\]; first contact tick by dy: (.*)$");
        foreach (var line in File.ReadAllLines(Path.Combine(HitOracleTrace.OutputFolder(), "reach-sweep.txt")))
        {
            var match = windowLine.Match(line);
            if (!match.Success)
            {
                continue;
            }

            var dx = int.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture);
            foreach (var item in match.Groups[4].Value.Split(", "))
            {
                var parts = item.Split(':');
                table[(dx, int.Parse(parts[0], CultureInfo.InvariantCulture))] = int.Parse(parts[1], CultureInfo.InvariantCulture);
            }
        }

        return table;
    }

    /// <summary>The row of pixels of the sweep's Beannoid: one tile row (16 px) above the oracle's 96, so that the hero 25 pixels south of it stays on the free cells (the wall of map 14 starts at pixel 128). A contact tick does not
    /// depend on a translation by whole tiles.</summary>
    private const int SweepY = 80;

    /// <summary>The tick at which the swing of a hero at (252 - dx, 80 + dy) first hits a Beannoid at (252, 80) (22 ticks, as the sweep), null for never.</summary>
    private static int? FirstContactTick(int dx, int dy)
    {
        using var arena = new HitArena($"reach-{dx}-{dy}", 252 - dx, SweepY + dy, new List<int[]> { new[] { 252, SweepY } });
        var samples = arena.RunSwing(22);
        return samples.Where(s => s.Targets[0].CooldownTicks == 25).Select(s => (int?)s.Tick).FirstOrDefault();
    }

