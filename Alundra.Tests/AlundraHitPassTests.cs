/// <summary>
/// E20.c1a C5 (docs/plan-e20-heros.md section 1.5): the hit pass of the DLL against the oracle of E20.c1 (<c>docs/plan-e20-annexe/e20-c1/oracle/out/</c>: the real code of <c>ALUN_CD.EXE</c> (France), the hero of D1 and real
/// Beannoid targets, regenerated by <c>run_c1.py</c>). The DLL side is the real world of map 14 with real prefabs (<see cref="HitArena"/>), the hero and the Beannoids carried to the flat cells of the oracle. After each tick
