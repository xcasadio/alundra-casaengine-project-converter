    /// <summary>Compares the samples to the rows of <paramref name="trace"/> up to <paramref name="lastTick"/>; <paramref name="ignore"/> (tick, entity index, field) excludes a cell. Returns every difference.</summary>
    internal static List<string> Compare(
        HitOracleTrace trace, IReadOnlyList<HitTickSample> samples, int lastTick = int.MaxValue, Func<int, int, string, bool>? ignore = null, bool sparks = true)
    {
        var diffs = new List<string>();
        var last = Math.Min(trace.Rows.Count, lastTick);
        if (samples.Count < last)
        {
            diffs.Add($"{trace.Name}: {samples.Count} ticks sampled, {last} expected");
            last = samples.Count;
        }

        for (var tick = 1; tick <= last; tick++)
        {
            var row = trace.Rows[tick - 1];
            var sample = samples[tick - 1];

            void Check(int entity, string field, long dll, long oracle)
            {
                if (dll != oracle && ignore?.Invoke(tick, entity, field) != true)
                {
                    diffs.Add($"{trace.Name} tick {tick} entity {entity} {field}: dll {dll}, oracle {oracle}");
                }
            }

            void CheckEntity(int index, HitEntitySample dll, HitOracleEntity oracle)
            {
                Check(index, "anim_target", dll.AnimTarget, oracle["anim_target"]);
                Check(index, "anim_flags_B4", dll.AnimByte, oracle["anim_flags_B4"]);
                Check(index, "frame_box", dll.HasBox ? 1 : 0, oracle.HasBox ? 1 : 0);
                if (oracle.HasBox && dll.HasBox)
                {
                    Check(index, "boff_x", dll.BoxOffsetX, oracle["boff_x"]);
                    Check(index, "boff_y", dll.BoxOffsetY, oracle["boff_y"]);
                    Check(index, "boff_z", dll.BoxOffsetZ, oracle["boff_z"]);
                    Check(index, "bsize_x", dll.BoxWidth, oracle["bsize_x"]);
                    Check(index, "bsize_y", dll.BoxDepth, oracle["bsize_y"]);
                    Check(index, "bsize_z", dll.BoxHeight, oracle["bsize_z"]);
                }

                Check(index, "atk_attr", dll.AttackAttribute, oracle["atk_attr"]);
                Check(index, "atk_power", dll.AttackPower, oracle["atk_power"]);
                Check(index, "touching_slot", dll.Touching, oracle.TouchingSlot);
                Check(index, "hit_counter", dll.HitCounter, oracle["hit_counter"]);
                Check(index, "c1cc", dll.DamagedTicks, oracle["c1cc"]);
                Check(index, "c1d0", dll.CooldownTicks, oracle["c1d0"]);
                Check(index, "hp", dll.Hp, oracle["hp"]);
            }

            CheckEntity(0, sample.Hero, row.Hero);
            Check(0, "pos_x", sample.Hero.PosX - (long)trace.HeroPixelX * 65536, row.Hero["pos_x"] - (long)trace.HeroPixelX * 65536);
            Check(0, "pos_y", sample.Hero.PosY - (long)trace.HeroPixelY * 65536, row.Hero["pos_y"] - (long)trace.HeroPixelY * 65536);
            for (var i = 0; i < row.Targets.Count && i < sample.Targets.Count; i++)
            {
                CheckEntity(i + 1, sample.Targets[i], row.Targets[i]);
            }

            Check(0, "latch", sample.Latch, row.Latch);

            var dllHandlers = string.Join(",", sample.Handlers.OrderBy(h => h.Slot).Select(h => $"{h.Slot}:{h.Letter}"));
            var oracleHandlers = string.Join(",", row.Handlers.OrderBy(h => h.Slot).Select(h => $"{h.Slot}:{h.Letter}"));
            if (dllHandlers != oracleHandlers && ignore?.Invoke(tick, -1, "handlers") != true)
            {
                diffs.Add($"{trace.Name} tick {tick} programs: dll [{dllHandlers}], oracle [{oracleHandlers}]");
            }

            if (sparks)
            {
                var dllSparks = string.Join(";", sample.Sparks.SelectMany(s => Enumerable.Repeat($"{s.X},{s.Y},{s.Z + 1}", NativeEffects.HitSparkCount)));
                var oracleSparks = string.Join(";", row.Sparks.Select(s => $"{s.X},{s.Y},{s.Z}"));
                if (dllSparks != oracleSparks && ignore?.Invoke(tick, -1, "sparks") != true)
                {
                    diffs.Add($"{trace.Name} tick {tick} sparks (x,y,z+1): dll [{dllSparks}], oracle [{oracleSparks}]");
                }
            }
        }

        return diffs;
    }

    internal static void AssertEqualToOracle(List<string> diffs)
        => Assert.True(diffs.Count == 0, $"{diffs.Count} differences with the oracle; the first ones:{Environment.NewLine}{string.Join(Environment.NewLine, diffs.Take(15))}");

    internal static HitArena Arena(HitOracleTrace trace, string name)
        => new(name, trace.HeroPixelX, trace.HeroPixelY, trace.TargetPixels, trace.Name == "H8" ? 8u : 24u);

    private static void WholeTraceEqualsTheOracle(string name)
    {
        var trace = HitOracleTrace.Load(name);
        using var arena = Arena(trace, name);
        var samples = arena.Run(trace, 1);
        AssertEqualToOracle(Compare(trace, samples));
    }

