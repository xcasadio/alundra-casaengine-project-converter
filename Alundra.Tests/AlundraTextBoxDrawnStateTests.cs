    private static DialogueAsset LoadMapAsset(string root, int mapId)
    {
        var file = Directory.GetFiles(Path.Combine(root, "Maps"), $"*-{mapId}.dialogue", SearchOption.AllDirectories)
            .Single(p => Path.GetFileNameWithoutExtension(p).EndsWith("-" + mapId, StringComparison.Ordinal));
        return DialogueTestAssets.LoadFromDisk(file);
    }

    private static void TypeThePage(int maxPasses = 800)
    {
        for (var pass = 0; pass < maxPasses && !Director.Box.IsTypingDone; pass++)
        {
            Director.Pass(false, false);
        }

        Assert.True(Director.Box.IsTypingDone);
    }

    [Fact]
    public void TheRealCentredLineOfThePub_S025OfMap472_IsCentredByTheProductionReaderOfFont3()
    {
        var root = SaveGameDirectorTestSupport.FindProjectRoot();
        EngineEnvironment.ProjectPath = root;
        AlundraFont3Advances.ResetForTests();

        OpenTheBox(LoadMapAsset(root, 472), "M472_S025");
        TypeThePage();
        var box = Director.Box;

        // 43 glyph steps (the 8 trailing spaces of the second line are typed, as in the binary: f2b1a), the widths of the binary (111 and 125 px) and their x.
        Assert.Equal(43, box.GlyphCount);
        Assert.Equal((111, 125), (box.RowWidth(0), box.RowWidth(1)));
        Assert.Equal((104, 97), (box.RowX(0), box.RowX(1)));
        Assert.Equal(32, box.RowX(2));
        Assert.Equal("Roue de la fortune !", box.Row(0));
        Assert.Equal("Florin" + (char)21 + "Roulette        ", box.Row(1));
    }

    [Fact]
    public void AProjectWithoutFont3_GivesWidthZeroAndX32_AndOneWarningPerProjectPath()
    {
        var empty = Path.Combine(Path.GetTempPath(), "alundra-no-font3-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(empty);
        using var logger = new WarningCapture();
        try
        {
            EngineEnvironment.ProjectPath = empty;
            AlundraFont3Advances.ResetForTests();

            OpenTheBox(Of("S3").Asset());
            TypeThePage();
            var box = Director.Box;
            Assert.Equal((0, 0), (box.RowWidth(0), box.RowWidth(1)));
            Assert.Equal((32, 32), (box.RowX(0), box.RowX(1)));
            Assert.Equal("Roue de la fortune !", box.Row(0));

            // Two centred lines, one box: the table is read once for the project path.
            var warnings = logger.Warnings.Where(w => w.Contains("font3.fnt", StringComparison.Ordinal)).ToList();
            Assert.True(warnings.Count == 1, $"{warnings.Count} warnings: {string.Join(" | ", warnings)}");
            Assert.Contains(empty, warnings[0], StringComparison.Ordinal);
        }
        finally
        {
            Directory.Delete(empty, recursive: true);
        }
    }

    private sealed class WarningCapture : ILogger, IDisposable
    {
        private readonly object _gate = new();
        private readonly List<string> _warnings = new();

        public WarningCapture()
        {
            Logs.AddLogger(this);
        }

        public List<string> Warnings
        {
            get
            {
                lock (_gate)
                {
                    return _warnings.ToList();
                }
            }
        }

        public void Close() { }
        public void WriteTrace(string msg) { }
        public void WriteDebug(string msg) { }
        public void WriteInfo(string msg) { }
        public void WriteError(string msg) { }

        public void WriteWarning(string msg)
        {
            lock (_gate)
            {
                _warnings.Add(msg);
            }
        }

        public void Dispose()
        {
            var field = typeof(Logs).GetField("_loggers", BindingFlags.Static | BindingFlags.NonPublic);
            Assert.NotNull(field);
            ((List<ILogger>)field!.GetValue(null)!).Remove(this);
        }
    }
