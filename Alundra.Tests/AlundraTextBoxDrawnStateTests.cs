/// <summary>
/// E19.f2b1b T1 (docs/plan-e19-opcodes.md, "E19.f2b1b - Etat dessine de la boite et oracle etendu"): the DRAWN state of the dialogue box - what the binary's
/// <c>MsgBoxRender</c> 0x80046EF0 puts in the ordering table at each pass - for the six scenarios of the annex (<c>docs/plan-e19-f2b1-annexe/values/S1.csv</c> to
/// <c>S6.csv</c>, generated by <c>scripts/scenarios.py</c> from <c>model_drawn.py</c>): the oracle (<see cref="AlundraTextBoxOracle"/>, extended, written from the model) equals
/// the tables in their own form, and the box (<see cref="AlundraDialogueBox"/>) equals them under one rule for the pass that ends a scroll. Pass 0 of a table is the pass of
/// the opening (no drawing); pass p is the p-th call of <see cref="AlundraDialogueDirector.Pass"/> after <see cref="AlundraDialogueDirector.Open"/>. The advances of the
/// glyphs come from the binary's own width table (the oracle's), injected into the director; the production reader of <c>UI/font3.fnt</c> is tested on the real export (S025
/// of map 472) and on a project without the file.
/// </summary>
