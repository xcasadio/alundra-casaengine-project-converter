    [Fact]
    public void B3_TheGroupsAreExactlyTheBinarysIds_TheGroundGroupLosesTheGround_TheAirGroupLandsIdle()
    {
        var ground = new uint[] { 0x04, 0x08, 0x09, 0x10, 0x11, 0x12, 0x13, 0x18, 0x19, 0x25, 0x3F, 0x40, 0x44, 0x49 };
        var air = new uint[] { 0x0A, 0x14, 0x15, 0x16, 0x17, 0x1F, 0x26, 0x41, 0x42, 0x46, 0x4B };
        var others = new uint[] { 0x0D, 0x1A, 0x43, 0x45, 0x47, 0x48, 0x4A }; // the default group of the binary (0x80032758): nothing is done to them by the port either.

        // On the ground: an id of the air group lands Idle (0); the others stay.
        var (onGround, _) = Start(AttackOracleTrace.Load("AT1"));
        foreach (var id in ground.Concat(air).Concat(others))
        {
            onGround.Hero.TargetAnimationId = id;
            onGround.Hero.CurrentAnimationId = id;
            onGround.Step();
            Assert.Equal(air.Contains(id) ? 0u : id, onGround.Hero.TargetAnimationId);
        }

        // In the air (a hero high above the floor, falling all along): an id of the ground group gives the air state 0x2D; the others stay.
        var inTheAir = JumpHeroRig.Build(z: 3000f, freePad: true, attackClock: true);
