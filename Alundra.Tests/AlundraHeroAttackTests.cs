    private static RecordingSoundPlayer InjectSounds(ArcRun arc)
    {
        var player = new RecordingSoundPlayer();
        typeof(AlundraWorldProxy).GetField("<SoundPlayer>k__BackingField", BindingFlags.Instance | BindingFlags.NonPublic)!.SetValue(arc.Proxy, player);
        return player;
    }

    /// <summary>Runs the arc until the hero stands free: Idle (the arrival animation chained away), no lock on the pad.</summary>
    private static void WaitUntilTheHeroIsFree(ArcRun arc)
    {
        for (var frame = 0; frame < 300 && !(arc.Hero.TargetAnimationId == 0u && arc.Hero.CurrentAnimationId == 0u && AlundraGameState.Instance.PlayerControlFlags == 0); frame++)
        {
            arc.OneFrame();
        }

        Assert.Equal(0u, arc.Hero.TargetAnimationId);
        Assert.Equal(0u, AlundraGameState.Instance.PlayerControlFlags);
    }

    [Fact]
    public void RealPrefab_TheHeroOfTheExport_SwingsTheBasicSwordOnTheGroundAndInTheAir_AtTheTicksOfTheOracle()
    {
        // The hero is the prefab of production (its 376 animations on the logical clock, the exported lengths and Chain ends), in a real world, with the free pad of the arc.
        using var arc = new ArcRun(FreeHeroSpec("E20b-prefab"));
        var sounds = InjectSounds(arc);
        var hero = arc.Hero;
        WaitUntilTheHeroIsFree(arc);
        arc.OneFrame();
        sounds.Requests.Clear();
        AlundraPlayerManager.InitializeNewGameInventory(AlundraGameState.Instance, ((IScriptHost)arc.Proxy).ItemTables!);

        // On the ground: the press at S asks the sound 29 at S, the swing 0x10 runs ticks S to S+20, Idle at S+21 (tick 22 of AT1).
        var swing = new List<uint>();
        arc.Press(Square);
        swing.Add(hero.TargetAnimationId);
        Assert.Equal(new[] { 29 }, sounds.Requests.ToArray());
        for (var i = 1; i <= 21; i++)
        {
            arc.OneFrame();
            swing.Add(hero.TargetAnimationId);
        }

        Assert.Equal(Enumerable.Repeat(0x10u, 21).Concat(new[] { 0u }).ToArray(), swing.ToArray());
        Assert.Equal(0u, hero.CurrentAnimationId);
        Assert.Equal(new[] { 29 }, sounds.Requests.ToArray()); // nothing else asked during the swing.
        Assert.Equal(0u, hero.WeaponRecordPointer);

        // In the air: the jump, then the Square at the 5th tick of the jump (AT3): 0x14 for 10 ticks, then the air state 0x2D.
        for (var i = 0; i < 4; i++)
        {
            arc.OneFrame();
        }

        sounds.Requests.Clear();
        arc.Press(Cross);
        Assert.Equal(0x2Bu, hero.TargetAnimationId); // the standing jump.
        for (var i = 1; i <= 3; i++)
        {
            arc.OneFrame();
        }

        Assert.Equal(0x2Du, hero.TargetAnimationId);
        Assert.Equal(0, hero.IsOnGround);
        sounds.Requests.Clear();
        arc.Press(Square);
        var air = new List<uint> { hero.TargetAnimationId };
        Assert.Equal(new[] { 29 }, sounds.Requests.ToArray());
        Assert.Equal(0x80028C7Du, hero.WeaponRecordPointer);
        for (var i = 1; i <= 10; i++)
        {
            arc.OneFrame();
            air.Add(hero.TargetAnimationId);
        }

        Assert.Equal(Enumerable.Repeat(0x14u, 10).Concat(new[] { 0x2Du }).ToArray(), air.ToArray());
    }

    [Fact]
    public void RealPrefab_TheTablesOfTheWorld_AreNotNull_AndASteelEdgePicksItsOwnRecord()
    {
        using var arc = new ArcRun(FreeHeroSpec("E20b-tables"));
        InjectSounds(arc);
        var hero = arc.Hero;
        var tables = ((IScriptHost)arc.Proxy).ItemTables;
        Assert.NotNull(tables);
        WaitUntilTheHeroIsFree(arc);
        arc.OneFrame();

        // The Steel Edge (item 2, slot 1, rank above the basic sword's) owned and equipped: the record 1, the swing 0x3F, the pointer at the record's own address.
        var state = AlundraGameState.Instance;
        AlundraPlayerManager.InitializeNewGameInventory(state, tables!);
        state.NumberOfItems[2 * 2 + 1] = 1;
        AlundraPlayerManager.SetPlayerWeaponId(state, tables!, 1);
        Assert.Equal(2u, AlundraPlayerManager.GetItemIdFromCurrentWeapon(state, tables!));
        arc.Press(Square);
        Assert.Equal(1, hero.CurrentWeaponRecord);
