    [Fact]
    public void AT8b_TheFloorDroppingUnderASwingingHero_GivesTheAirState()
    {
        var trace = AttackOracleTrace.Load("AT8b");
        var field = FlatCells.Create(cell: (_, _) => (0, 1));
        var (rig, sounds) = Start(trace, field);
        var heights = (int[])typeof(AlundraCellsCollisionField).GetField("_cellHeight", BindingFlags.Instance | BindingFlags.NonPublic)!.GetValue(field)!;
        var tickNow = 0;
        rig.Host.BeforeTicks = () =>
        {
            if (tickNow == 7)
            {
                Array.Fill(heights, 0); // the harness of the oracle lowers every cell to 0 just before tick 7: here, like a map event of the tick, after the head pull of the frame.
            }
        };

        // A floor lost under a motionless hero is read by the engine one tick after the binary's physics pass (the pull of the head of the frame, E19.d2c1 R6, the same
        // representation as UH7): the DLL's fall (ForceZ, PosZ, IsOnGround) is one tick behind the oracle's from tick 7 to its landing, and so is the return to Idle after it
        // (tick 16 instead of 15). That is the existing fall, not the attack groups, so those columns are not compared there; everything else is, the animations first: the group
        // keeps the swing at tick 7 (it still reads the ground of the tick before) and gives the air state at tick 8, as the binary.
        var diffs = Compare(rig, sounds, trace, before: tick => tickNow = tick, ignore: (tick, field) => (tick is >= 7 and <= 15 && field is "force_z" or "pos_z" or "on_ground") || (tick == 15 && field is "anim_target" or "anim_cur"));
        AssertEqualToOracle(diffs);
    }

