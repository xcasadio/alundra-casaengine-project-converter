    /// <summary>The new-game inventory (the kit: the basic sword equipped), then <paramref name="item"/> owned and its slot equipped, or no weapon at all.</summary>
    private static void Equip(ContactHost host, int? item = null, bool noWeapon = false)
    {
        var tables = Tables();
        host.ItemTables = tables;
        AlundraPlayerManager.InitializeNewGameInventory(host.GameState, tables);
        if (item is { } id)
        {
            host.GameState.NumberOfItems[id * 2 + 1] = 1;
            AlundraPlayerManager.SetPlayerWeaponId(host.GameState, tables, tables.ItemsProperties[id * 5]);
        }

        if (noWeapon)
        {
            AlundraPlayerManager.SetPlayerWeaponId(host.GameState, tables, -1);
        }
    }

    /// <summary>
    /// The hero montage in the state the trace starts from: at the trace's position (X, Y, Z), with the sprite clock of the swings, facing east, settled (one frame at rest, the first
    /// switch resolved), then the trace's animation, forces and facing posed. The weapon is the kit's unless <paramref name="item"/> or <paramref name="noWeapon"/> says otherwise
    /// (<paramref name="withTables"/> false: a host with no item tables, the binary's "no weapon").
    /// </summary>
    private static (JumpHeroRig Rig, RecordingSoundPlayer Sounds) Start(
        AttackOracleTrace trace, ICollisionField? field = null, int? item = null, bool noWeapon = false, bool withTables = true)
    {
        var start = trace.Start;
        var rig = JumpHeroRig.Build(field, x: start.PosX / 65536f, y: start.PosY / 65536f, z: start.PosZDll / 65536f, freePad: true, attackClock: true);
        var sounds = new RecordingSoundPlayer();
        rig.Host.SoundPlayer = sounds;
        if (withTables)
        {
            Equip(rig.Host, item, noWeapon);
        }

        var hero = rig.Hero;
        hero.TargetDirection = 24;
        hero.AnimationDirection = 3; // right: east.
        hero.CurrentAnimationId = ~hero.TargetAnimationId;
        rig.Step(); // the first switch (the sprite takes the animation 0, right) is resolved: nothing pending at tick 1.
        sounds.Requests.Clear();

        if (start.AnimTarget != 0)
        {
            hero.TargetAnimationId = start.AnimTarget;
            hero.CurrentAnimationId = start.AnimTarget;
        }

        hero.TargetDirection = (uint)start.DirTarget;
        hero.ForceX = start.ForceX;
        hero.ForceY = start.ForceY;
        hero.ForceZ = start.ForceZ;
        return (rig, sounds);
    }

    /// <summary>
    /// Steps the montage over the rows of <paramref name="trace"/> (the pad word of the row held, one tick per frame) and returns every difference with the oracle, as
    /// "name tick N field: dll X, oracle Y". <paramref name="before"/> runs before the step of a tick (a harness change of the field); <paramref name="lastTick"/> stops early.
    /// </summary>
    private static List<string> Compare(
        JumpHeroRig rig, RecordingSoundPlayer sounds, AttackOracleTrace trace, Action<int>? before = null, int lastTick = int.MaxValue, int[]? onGroundLag = null, Func<int, string, bool>? ignore = null)
    {
        var onGroundLagTicks = onGroundLag ?? Array.Empty<int>();
        var diffs = new List<string>();
        var hero = rig.Hero;
        var (startX, startY) = (hero.PosX, hero.PosY);
        foreach (var row in trace.Rows.TakeWhile(r => r.Tick <= lastTick))
        {
            sounds.Requests.Clear();
            var spawnsBefore = AlundraPlayerManager.WeaponSpawnCallCountForTests;
            before?.Invoke(row.Tick);
            rig.Step(row.Hold);

            void Check(string field, long dll, long oracle)
            {
                if (dll != oracle && ignore?.Invoke(row.Tick, field) != true)
                {
                    diffs.Add($"{trace.Name} tick {row.Tick} {field}: dll {dll}, oracle {oracle}");
                }
            }

            Check("anim_target", hero.TargetAnimationId, row.AnimTarget);
            Check("anim_cur", hero.CurrentAnimationId, row.AnimCur);
            Check("dir_target", hero.TargetDirection, row.DirTarget);
            Check("force_x", hero.ForceX, row.ForceX);
            Check("force_y", hero.ForceY, row.ForceY);
            Check("force_z", hero.ForceZ, row.ForceZ);
            Check("pos_x", hero.PosX - startX, row.PosX - trace.Start.PosX);
            Check("pos_y", hero.PosY - startY, row.PosY - trace.Start.PosY);
            Check("pos_z", hero.PosZ, row.PosZDll);
            // IsOnGround is pulled from the engine at the head of the frame (E19.d2c1 R6): after a walk off a ledge the DLL reads the loss one tick after the binary
            // computed it in its physics pass (the same one-tick representation as UH7). The listed ticks compare it to the oracle's value of the tick before; the decisions
            // of MovePlayer (the next tick's) are what the other fields check.
            var previous = row.Tick == 1 ? trace.Start : trace.Rows[row.Tick - 2];
            Check("on_ground", hero.IsOnGround, onGroundLagTicks.Contains(row.Tick) ? previous.OnGround : row.OnGround);
            Check("rec_ptr", hero.WeaponRecordPointer, row.RecPtr);
            Check("rec_cnt", hero.WeaponStepCounter, row.RecCnt);
            Check("spawns", AlundraPlayerManager.WeaponSpawnCallCountForTests - spawnsBefore, row.Spawns);
            // The landing sound 11 (and its dust, the effect 0x8003BDD8) is asked by the binary's landing code, which the DLL has as a named stub (E20.f2: AlundraPlayerAnimationEffects.PlayerLandingEffects, E20.e fills it): outside E20.b.
            var dllSounds = string.Join(",", sounds.Requests.Where(s => s != LandingSound).OrderBy(s => s));
            var oracleSounds = string.Join(",", row.Sounds.Where(s => s != LandingSound).OrderBy(s => s));
            if (dllSounds != oracleSounds)
            {
                diffs.Add($"{trace.Name} tick {row.Tick} sounds: dll [{dllSounds}], oracle [{oracleSounds}]");
            }
        }

        return diffs;
    }

    private static void AssertEqualToOracle(List<string> diffs)
        => Assert.True(diffs.Count == 0, $"{diffs.Count} differences with the oracle; the first ones:{Environment.NewLine}{string.Join(Environment.NewLine, diffs.Take(12))}");

    private static void Run(string name, ICollisionField? field = null, int? item = null, bool noWeapon = false, bool walking = false, int[]? onGroundLag = null)
    {
        var trace = AttackOracleTrace.Load(name);
        var (rig, sounds) = Start(trace, field, item, noWeapon);
        AssertEqualToOracle(Compare(rig, sounds, trace, onGroundLag: onGroundLag));
        Assert.Equal(walking, trace.Start.AnimTarget == 1);
    }

