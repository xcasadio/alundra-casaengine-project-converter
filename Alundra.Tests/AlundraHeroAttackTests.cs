    {
        var lines = File.ReadAllLines(Path.Combine(AttackOracleTrace.OutputFolder(), "at7-cellmap.txt")).Where(l => l.StartsWith("cell col", StringComparison.Ordinal)).ToList();
        Assert.Equal(25, lines.Count);
        var blocked = 0;
        foreach (var line in lines)
        {
            var match = Regex.Match(line, @"^cell col (\d+) row (\d+) \| \+0x180 = 0x([0-9A-F]+) \| swing (YES|no)");
            Assert.True(match.Success, line);
            var (col, row) = (int.Parse(match.Groups[1].Value), int.Parse(match.Groups[2].Value));
            var swings = match.Groups[4].Value == "YES";

            var (rig, _) = Start(AttackOracleTrace.Load("AT1"), Flagged((c, r) => c == col && r == row));
            rig.Step(Square);
            Assert.True(swings == (rig.Hero.TargetAnimationId == 0x10u), $"cell ({col},{row}): swing {rig.Hero.TargetAnimationId == 0x10u}, the oracle says {swings}");
            Assert.True(swings == (rig.Hero.WeaponRecordPointer != 0), $"cell ({col},{row}): record pointer {rig.Hero.WeaponRecordPointer:X}");
            blocked += swings ? 0 : 1;
        }

        Assert.Equal(4, blocked); // the four cells (3, 5), (4, 5), (3, 6), (4, 6).
    }

