    [Fact]
    public void AT6Sweep_APressOnTheChainTickIsLost_TheFirstAcceptedIsTheNextTick()
    {
        var lines = File.ReadAllLines(Path.Combine(AttackOracleTrace.OutputFolder(), "at6-sweep.txt")).Where(l => l.StartsWith("p=", StringComparison.Ordinal)).ToList();
        Assert.Equal(8, lines.Count);
        foreach (var line in lines)
        {
            var match = Regex.Match(line, @"^p=\s*(\d+) \| second swing (YES|no)");
            Assert.True(match.Success, line);
            var p = int.Parse(match.Groups[1].Value);
            var expectSecondSwing = match.Groups[2].Value == "YES";

            var (rig, _) = Start(AttackOracleTrace.Load("AT1"));
            var secondSwingAtP = false;
            for (var tick = 1; tick <= p; tick++)
            {
                rig.Step(tick == 1 || tick == p ? Square : 0);
                secondSwingAtP = tick == p && rig.Hero.WeaponRecordPointer != 0;
            }

            Assert.True(expectSecondSwing == secondSwingAtP, $"p={p}: second swing {secondSwingAtP}, the oracle says {expectSecondSwing}");
            Assert.Equal(expectSecondSwing ? 0x10u : p == 22 ? 0u : 0x10u, rig.Hero.TargetAnimationId);
        }
    }

