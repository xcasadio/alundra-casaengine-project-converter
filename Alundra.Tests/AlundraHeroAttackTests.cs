        }
    }

    [Fact]
    public void B6_AFrameOfTwoTicks_TheReturnThenANewPress_AsksTheSoundOfTheSecondSwing()
    {
        // Ticks 1 to 21: the swing, one tick per frame. Then ONE frame of two ticks: tick 22 is the return (the clock raises the Chain to Idle), tick 23 a new press. The binary asks
        // the sound 29 at the change of animation of tick 23 (0x80038BB0, every change); the first tick's Chain took the impulse and its lock must not swallow the second switch.
        var (rig, sounds) = Start(AttackOracleTrace.Load("AT1"));
        var hero = rig.Hero;
        for (var tick = 1; tick <= 21; tick++)
        {
            rig.Step(tick == 1 ? Square : 0);
        }

        Assert.Equal(new[] { 29 }, sounds.Requests.ToArray());
        Assert.Equal(0x10u, hero.TargetAnimationId);

        sounds.Requests.Clear();
        var released = new AlundraPadState();
        var pressed = new AlundraPadState { ButtonsHold = Square, ButtonsJustPressed = Square };
        hero.MovePlayerOnTickPad(in released); // tick 22: still the swing (the press of tick 22 would be lost).
        hero.TickAnimationClock();
        hero.TickPhysics();
        Assert.Equal(0u, hero.TargetAnimationId); // the Chain was raised by the clock of tick 22.
        hero.MovePlayerOnTickPad(in pressed); // tick 23: Idle, the new press.
        hero.TickAnimationClock();
        hero.TickPhysics();
        FrameSyncPasses.SyncAnimation(rig.HeroEntity);

        Assert.Equal(0x10u, hero.TargetAnimationId);
        Assert.Equal(0x10u, hero.CurrentAnimationId);
        Assert.Equal(new[] { 29 }, sounds.Requests.ToArray());
    }

